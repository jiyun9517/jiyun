def preprocess_malicious(df):
    # 주소 열 찾기
    url_col = "url" if "url" in df.columns else df.columns[0]
    # 라벨 열 찾기 (보통 'type' 또는 'label')
    label_col = "type" if "type" in df.columns else ("label" if "label" in df.columns else df.columns[1])

    temp = pd.DataFrame({
        "url": df[url_col],
        "raw_label": df[label_col]
    })

    # 결측치 제거 및 문자열 정리
    temp = temp.dropna(subset=["url", "raw_label"]).copy()
    temp["url"] = temp["url"].astype(str).str.strip()
    temp["raw_label"] = temp["raw_label"].astype(str).str.strip().str.lower()

    # 'benign' 또는 '0'이면 0(안전), 그 외 악성/피싱/악성코드/변조는 1(위험)
    temp["label"] = temp["raw_label"].apply(lambda x: 0 if x in ["benign", "0", "legitimate", "good"] else 1)
    return temp[["url", "label"]]


def preprocess_phiusiil(df):
    # PhiUSIIL 데이터셋은 보통 'URL'과 'label' 열을 가짐 (대소문자/이름 차이 대비)
    url_candidates = ["URL", "url", "Url"]
    label_candidates = ["label", "Label", "CLASS_LABEL", "type"]

    url_col = next((c for c in url_candidates if c in df.columns), df.columns[0])
    label_col = next((c for c in label_candidates if c in df.columns), df.columns[1])

    temp = pd.DataFrame({
        "url": df[url_col],
        "raw_label": df[label_col]
    })

    temp = temp.dropna(subset=["url", "raw_label"]).copy()
    temp["url"] = temp["url"].astype(str).str.strip()

    # PhiUSIIL에서 1이 legitimate(정상)이고 0이 phishing(피싱)인 경우가 있으므로 안전하게 변환
    def map_phi_label(val):
        s = str(val).strip().lower()
        if s in ["legitimate", "benign", "good"]:
            return 0
        if s in ["phishing", "malicious", "bad"]:
            return 1
        # 숫자인 경우: PhiUSIIL 표준은 1=정상, 0=피싱이므로 반전
        try:
            num = int(float(s))
            if num == 1:
                return 0 # 정상 -> 0
            elif num == 0:
                return 1 # 피싱 -> 1
        except ValueError:
            pass
        return 1

    temp["label"] = temp["raw_label"].apply(map_phi_label)
    return temp[["url", "label"]]


