HTML_FEATURE_NAMES = [
    "html_reachable",        # 접속 성공 여부 (1: 성공, 0: 실패)
    "hidden_iframe_count",   # 숨겨진 iframe 개수 (display:none, visibility:hidden, 0px 크기 등)
    "external_link_count",   # 외부 도메인으로 연결되는 <a> 링크 수
    "form_count",            # 입력 폼(<form>) 개수
    "password_input_count",  # 비밀번호 입력칸(<input type='password'>) 개수
    "script_count",          # <script> 태그 개수
]

def extract_html_features(url, timeout=3.0):
    url = str(url).strip()
    target_url = url if url.startswith(("http://", "https://")) else "http://" + url
    base_domain = urlparse(target_url).netloc.lower()

    headers = {
        "User-Agent": (
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
            "AppleWebKit/537.36 (KHTML, like Gecko) "
            "Chrome/120.0.0.0 Safari/537.36"
        )
    }

    try:
        resp = requests.get(target_url, headers=headers, timeout=timeout, allow_redirects=True)
        html_text = resp.text
        soup = BeautifulSoup(html_text, "html.parser")

        # 1) 숨겨진 iframe 개수
        hidden_iframe_count = 0
        for iframe in soup.find_all("iframe"):
            style = (iframe.get("style") or "").replace(" ", "").lower()
            width = str(iframe.get("width") or "").strip()
            height = str(iframe.get("height") or "").strip()
            hidden_attr = iframe.has_attr("hidden")

            is_hidden = (
                hidden_attr
                or "display:none" in style
                or "visibility:hidden" in style
                or width in ["0", "0px"]
                or height in ["0", "0px"]
            )
            if is_hidden:
                hidden_iframe_count += 1

        # 2) 외부 링크 수
        external_link_count = 0
        for a in soup.find_all("a", href=True):
            href = a["href"].strip()
            if not href or href.startswith(("#", "javascript:", "mailto:", "tel:")):
                continue
            full_href = urljoin(resp.url, href)
            link_domain = urlparse(full_href).netloc.lower()
            if link_domain and base_domain and link_domain != base_domain:
                external_link_count += 1

        # 3) 입력 폼(<form>) 개수
        form_count = len(soup.find_all("form"))

        # 4) 비밀번호 입력칸 개수
        password_input_count = len(soup.find_all("input", attrs={"type": re.compile(r"^password$", re.I)}))

        # 5) <script> 태그 개수
        script_count = len(soup.find_all("script"))

        return [
            1,
            hidden_iframe_count,
            external_link_count,
            form_count,
            password_input_count,
            script_count,
        ]

    except Exception:
        # 접속 불가/차단/타임아웃 시 안전하게 기본값 반환
        return [0, 0, 0, 0, 0, 0]


def extract_combined_features(url, include_html=True, timeout=3.0):
    url_feats = extract_url_features(url)
    if include_html:
        html_feats = extract_html_features(url, timeout=timeout)
    else:
        html_feats = [0] * len(HTML_FEATURE_NAMES)
    return url_feats + html_feats


